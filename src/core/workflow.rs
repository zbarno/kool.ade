#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TurnPurpose {
    #[default]
    Interview,
    /// Apply a persisted independent-review verdict to a specific plan candidate.
    PlanRemediation,
    /// Answer an investigative question without creating a feature spec.
    Question,
    /// Refresh a stale brief for an already authorized generation action.
    ReviewForGeneration,
    GenerateTasks,
    ComparePlans,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct InterviewBrief {
    #[serde(alias = "feature_name")]
    pub feature_name: String,
    pub problem: String,
    pub goal: String,
    #[serde(alias = "target_users")]
    pub target_users: String,
    #[serde(alias = "intended_outcome")]
    pub intended_outcome: String,
    #[serde(alias = "success_criteria")]
    pub success_criteria: Vec<String>,
    #[serde(alias = "in_scope")]
    pub in_scope: Vec<String>,
    #[serde(alias = "out_of_scope")]
    pub out_of_scope: Vec<String>,
    pub constraints: Vec<String>,
    #[serde(alias = "ready_for_tasks")]
    pub ready_for_tasks: bool,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Workflow {
    pub brief: Option<InterviewBrief>,
    /// The exact specification the readiness assessment covers.
    pub reviewed_specification: Option<String>,
    pub task_batches: Vec<TaskBatchRef>,
    #[serde(default)]
    pub approved_features: std::collections::BTreeMap<String, String>,
    /// Authoritative plan comparison lifecycle, keyed by stable feature ID.
    #[serde(default)]
    pub plan_comparisons: std::collections::BTreeMap<String, PlanComparisonRecord>,
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub feature_branch_targets: std::collections::BTreeMap<String, BranchTargets>,
    /// Unvalidated pre-contract comparison snapshots kept as history only.
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub legacy_plan_comparison_evidence:
        std::collections::BTreeMap<String, Vec<crate::domain::PlanComparison>>,
    /// Per-record concurrency metadata loaded from normalized workflow files.
    /// These fields are intentionally absent from serialized workflow data.
    #[serde(skip)]
    #[doc(hidden)]
    pub record_revisions: std::collections::BTreeMap<String, u64>,
    #[serde(skip)]
    #[doc(hidden)]
    pub record_baselines: std::collections::BTreeMap<String, String>,
    #[serde(skip)]
    #[doc(hidden)]
    pub feature_record_ids: std::collections::BTreeMap<String, String>,
}

impl PartialEq for Workflow {
    fn eq(&self, other: &Self) -> bool {
        self.brief == other.brief
            && self.reviewed_specification == other.reviewed_specification
            && self.task_batches == other.task_batches
            && self.approved_features == other.approved_features
            && self.plan_comparisons == other.plan_comparisons
            && self.feature_branch_targets == other.feature_branch_targets
            && self.legacy_plan_comparison_evidence == other.legacy_plan_comparison_evidence
    }
}

impl Eq for Workflow {}

