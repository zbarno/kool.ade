impl TrustedArgument {
    pub(in crate::app::bootstrap_remediation) fn apt_source_options() -> Vec<Self> {
        vec![
            Self::AptRootDirSystem,
            Self::AptSourceList,
            Self::AptSourceParts,
            Self::AptStateLists,
            Self::AptListCleanupTrue,
            Self::AptArchitectureAmd64,
            Self::AptUnauthenticatedFalse,
            Self::AptInsecureRepositoriesFalse,
            Self::AptWeakRepositoriesFalse,
            Self::AptDowngradeToInsecureFalse,
            Self::AptCheckDateTrue,
            Self::AptCheckValidUntilTrue,
            Self::AptHttpsVerifyPeerTrue,
            Self::AptHttpsVerifyHostTrue,
        ]
    }

    pub(in crate::app::bootstrap_remediation) fn version_probe_arguments(
        version_argument: Self,
    ) -> Vec<Self> {
        match version_argument {
            Self::DnfVersion => vec![Self::DnfCachedir, Self::DnfSystemCachedir, Self::DnfVersion],
            version_argument => vec![version_argument],
        }
    }
}
