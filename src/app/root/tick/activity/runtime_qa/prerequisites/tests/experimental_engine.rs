#[test]
fn experimental_runtime_qa_requires_native_rootless_linux_amd64() {
    assert!(super::super::experimental_engine_supported(
        true,
        true,
        Some(true),
        Some("amd64"),
        false
    ));
    assert!(!super::super::experimental_engine_supported(
        false,
        true,
        Some(true),
        Some("amd64"),
        false
    ));
    assert!(!super::super::experimental_engine_supported(
        true,
        false,
        Some(true),
        Some("amd64"),
        false
    ));
    assert!(!super::super::experimental_engine_supported(
        true,
        true,
        Some(false),
        Some("amd64"),
        false
    ));
    assert!(!super::super::experimental_engine_supported(
        true,
        true,
        None,
        Some("amd64"),
        false
    ));
    assert!(!super::super::experimental_engine_supported(
        true,
        true,
        Some(true),
        Some("arm64"),
        false
    ));
    assert!(!super::super::experimental_engine_supported(
        true,
        true,
        Some(true),
        Some("amd64"),
        true
    ));
}
